/** Each glyph as 8 rows of 8 bits, emboldened, the top row and the right column empty. */
const TILES = new Map(
  Object.entries(GLYPHS).map(([ch, rows]) => [
    ch,
    [0, ...rows.split(" ").map((r) => {
      const bits = parseInt(r, 2) << 2; // in columns 1…5 of 8
      return bits | (bits >> 1);
    })],
  ]),
);

/** Text as the font has it: capitals, and what it can't draw made a space. */
export const fontText = (s) =>
  String(s ?? "")
    .toUpperCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[→]/g, ">")
    .replace(/./gu, (c) => (TILES.has(c) ? c : " "));

/** A character's tile: 8 rows of 8 bits, the leftmost the high bit (a space when the font hasn't got it). */
export const tile = (ch) => TILES.get(fontText(ch)[0] ?? " ") ?? TILES.get(" ");

/** Draws `text` with its top-left at (x, y), 8 pixels a letter, in `color`. */
export function text(ctx, s, x, y, color) {
  ctx.fillStyle = color;
  let cx = x;
  for (const ch of fontText(s)) {
    const tile = TILES.get(ch);
    for (let r = 0; r < 8; r++) {
      const bits = tile[r];
      if (!bits) continue;
      // Runs of set bits as one rectangle each.
      for (let c = 0; c < 8; ) {
        if (bits & (0x80 >> c)) {
          let n = 1;
          while (c + n < 8 && bits & (0x80 >> (c + n))) n++;
          ctx.fillRect(cx + c, y + r, n, 1);
          c += n;
        } else c++;
      }
    }
    cx += 8;
  }
}
